import fs from "node:fs";

let failed = 0;
const check = (ok, message) => { console.log(`${ok ? "PASS" : "FAIL"}  ${message}`); if (!ok) failed++; };
const read = (path) => fs.readFileSync(path, "utf8");
const required = ["app/canonical.css", "app/styles/canonical-public.css", "app/layout.tsx"];
for (const file of required) check(fs.existsSync(file), `current UI owner exists: ${file}`);
const css = ["app/canonical.css", "app/styles/canonical-public.css"].filter(fs.existsSync).map(read).join("\n");
const layout = read("app/layout.tsx");
check(/:focus-visible/.test(css), "focus-visible support retained");
check(/min-height:\s*(?:44|46|48|50)px/.test(css), "touch target sizing support retained");
check(/prefers-reduced-motion/.test(css), "reduced-motion support retained");
check(/@media\s*\(max-width:\s*(?:480|620|640|760)px\)/.test(css), "mobile responsive coverage retained");
check(/(?:768px|900px|980px|1100px)/.test(css), "tablet/desktop responsive coverage retained");
check(layout.includes('import "./canonical.css";') && layout.includes('import "./styles/canonical-public.css";'), "canonical UI layers are globally loaded");
check(!css.includes("!important"), "canonical CSS remains !important-free");
const e2ePath = "tests/e2e/phase13-responsive-accessibility.spec.ts";
if (fs.existsSync(e2ePath)) check(/aria|focus-visible/.test(read(e2ePath)), "responsive accessibility e2e references accessibility behavior");
else console.log("INFO  Browser accessibility spec is not installed; static accessibility contracts remain authoritative for this gate.");
if (failed) process.exit(1);
console.log("\nProduct accessibility + responsive verification passed.");
